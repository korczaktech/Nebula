//! Representação semântica dos operadores sintáticos.

use crate::lexer::TipoToken;

/// Operadores reconhecidos pela gramática da Nebula.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum OperadorAst {
    Atribuicao,
    SomaAtribuicao,
    SubtracaoAtribuicao,
    MultiplicacaoAtribuicao,
    DivisaoAtribuicao,
    DivisaoInteiraAtribuicao,
    RestoAtribuicao,
    PotenciaAtribuicao,
    CoalesceAtribuicao,
    Igual,
    Identico,
    Diferente,
    DiferenteEstrito,
    Menor,
    MenorIgual,
    Maior,
    MaiorIgual,
    Adicao,
    Subtracao,
    Multiplicacao,
    Divisao,
    DivisaoInteira,
    Resto,
    Potencia,
    E,
    Ou,
    Negacao,
    EBit,
    OuBit,
    XorBit,
    NaoBit,
    DeslocamentoEsquerda,
    DeslocamentoDireita,
    DeslocamentoDireitaSemSinal,
    Coalesce,
    AcessoOpcional,
    Incremento,
    Decremento,
    Interrogacao,
    Seta,
    Intervalo,
    Espalhamento,
    Dentro,
    Fora,
    TipoDe,
    InstanciaDe,
    AcessoMembro,
    AcessoEscopo,
}

impl TryFrom<TipoToken> for OperadorAst {
    type Error = TipoToken;

    fn try_from(token: TipoToken) -> Result<Self, Self::Error> {
        match token {
            TipoToken::Atribui => Ok(Self::Atribuicao),
            TipoToken::SomaAtribui => Ok(Self::SomaAtribuicao),
            TipoToken::SubtraiAtribui => Ok(Self::SubtracaoAtribuicao),
            TipoToken::MultiplicaAtribui => Ok(Self::MultiplicacaoAtribuicao),
            TipoToken::DivideAtribui => Ok(Self::DivisaoAtribuicao),
            TipoToken::DivideInteiraAtribui => Ok(Self::DivisaoInteiraAtribuicao),
            TipoToken::RestoAtribui => Ok(Self::RestoAtribuicao),
            TipoToken::PotenciaAtribui => Ok(Self::PotenciaAtribuicao),
            TipoToken::CoalesceAtribui => Ok(Self::CoalesceAtribuicao),
            TipoToken::Igual | TipoToken::Iguais | TipoToken::IgualLegado => Ok(Self::Igual),
            TipoToken::Identico => Ok(Self::Identico),
            TipoToken::Diferente => Ok(Self::Diferente),
            TipoToken::DiferenteEstrito => Ok(Self::DiferenteEstrito),
            TipoToken::Menor | TipoToken::MenorLegado => Ok(Self::Menor),
            TipoToken::MenorIgual => Ok(Self::MenorIgual),
            TipoToken::Maior | TipoToken::MaiorLegado => Ok(Self::Maior),
            TipoToken::MaiorIgual => Ok(Self::MaiorIgual),
            TipoToken::Mais => Ok(Self::Adicao),
            TipoToken::Menos => Ok(Self::Subtracao),
            TipoToken::Vezes => Ok(Self::Multiplicacao),
            TipoToken::Divide => Ok(Self::Divisao),
            TipoToken::DivideInteira => Ok(Self::DivisaoInteira),
            TipoToken::Resto => Ok(Self::Resto),
            TipoToken::Potencia => Ok(Self::Potencia),
            TipoToken::E | TipoToken::ELogico => Ok(Self::E),
            TipoToken::Ou | TipoToken::OuLogico => Ok(Self::Ou),
            TipoToken::Nao | TipoToken::Negacao => Ok(Self::Negacao),
            TipoToken::EBit => Ok(Self::EBit),
            TipoToken::OuBit => Ok(Self::OuBit),
            TipoToken::XorBit => Ok(Self::XorBit),
            TipoToken::NaoBit => Ok(Self::NaoBit),
            TipoToken::DeslocaEsquerda => Ok(Self::DeslocamentoEsquerda),
            TipoToken::DeslocaDireita => Ok(Self::DeslocamentoDireita),
            TipoToken::DeslocaDireitaSemSinal => Ok(Self::DeslocamentoDireitaSemSinal),
            TipoToken::Coalesce => Ok(Self::Coalesce),
            TipoToken::AcessoOpcional => Ok(Self::AcessoOpcional),
            TipoToken::Incrementa => Ok(Self::Incremento),
            TipoToken::Decrementa => Ok(Self::Decremento),
            TipoToken::Interrogacao => Ok(Self::Interrogacao),
            TipoToken::Seta => Ok(Self::Seta),
            TipoToken::Intervalo => Ok(Self::Intervalo),
            TipoToken::Reticencias => Ok(Self::Espalhamento),
            TipoToken::Dentro => Ok(Self::Dentro),
            TipoToken::Fora => Ok(Self::Fora),
            TipoToken::TipoDe => Ok(Self::TipoDe),
            TipoToken::InstanciaDe => Ok(Self::InstanciaDe),
            TipoToken::Ponto => Ok(Self::AcessoMembro),
            TipoToken::Escopo => Ok(Self::AcessoEscopo),
            outro => Err(outro),
        }
    }
}
